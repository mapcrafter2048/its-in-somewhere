import * as THREE from 'three';
import { DESKTOP_Y } from '../hub-layout';
/** Two small authored details; canvases are created once with the work nook. */
export function addOfficeDetails(root: THREE.Group, unit: THREE.BufferGeometry) {
    const ring = document.createElement('canvas');
    ring.width = ring.height = 128;
    const ink = ring.getContext('2d')!;
    ink.strokeStyle = 'rgba(69,42,23,.24)';
    ink.lineWidth = 4;
    ink.beginPath();
    ink.ellipse(63, 64, 46, 43, .1, .15, Math.PI * 1.88);
    ink.stroke();
    ink.strokeStyle = 'rgba(69,42,23,.12)';
    ink.lineWidth = 2;
    ink.beginPath();
    ink.ellipse(64, 64, 42, 40, 0, 0, Math.PI * 2);
    ink.stroke();
    const texture = new THREE.CanvasTexture(ring);
    texture.colorSpace = THREE.SRGBColorSpace;
    const stain = new THREE.Mesh(unit, new THREE.MeshBasicMaterial({ map: texture, transparent: true, depthWrite: false }));
    stain.name = 'old-mug-ring';
    stain.position.set(-.83, DESKTOP_Y + .0015, .23);
    stain.scale.set(.22, .001, .22);
    root.add(stain);
    const paper = document.createElement('canvas');
    paper.width = 256;
    paper.height = 320;
    const ctx = paper.getContext('2d')!;
    ctx.fillStyle = '#d4c9a8';
    ctx.fillRect(0, 0, 256, 320);
    ctx.fillStyle = '#535c48';
    ctx.textAlign = 'center';
    ctx.font = 'bold 20px monospace';
    ['PLEASE LEAVE', 'THIS NOTICE', 'WHERE YOU', 'FOUND IT.'].forEach((line, index) => ctx.fillText(line, 128, 84 + index * 34));
    ctx.strokeStyle = '#72775d';
    ctx.beginPath();
    ctx.moveTo(35, 246);
    ctx.lineTo(220, 244);
    ctx.stroke();
    ctx.font = 'italic 17px Georgia';
    ctx.fillText('Location under review.', 128, 274);
    ctx.fillStyle = '#8b5949';
    ctx.beginPath();
    ctx.arc(128, 20, 5, 0, Math.PI * 2);
    ctx.fill();
    const map = new THREE.CanvasTexture(paper);
    map.colorSpace = THREE.SRGBColorSpace;
    const notice = new THREE.Mesh(unit, new THREE.MeshStandardMaterial({ map, roughness: 1 }));
    notice.name = 'corrected-office-notice';
    notice.position.set(2.4, 2.65, -1.3);
    notice.rotation.z = -.05;
    notice.scale.set(.33, .42, .006);
    root.add(notice);
}
